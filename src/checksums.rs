// get the checksum modifier for a number in a specific column
pub fn get_checksum_modifier(column_num: usize, num: u8) -> u16 {
    let mut checksum_mod: u16 = 0;

    for i in 0..8 {
        if num & 1 << i > 0 {
            checksum_mod ^= CHECKSUM_MODIFIERS[column_num][i];
        }
    }
    checksum_mod
}
